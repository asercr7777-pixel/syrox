export const ALL_CHAPTERS: StoryChapter[] = [...STORY_CHAPTERS, ...STORY_CHAPTERS_EXPANSION];

export function getChapterById(id: string): StoryChapter | undefined {
  return ALL_CHAPTERS.find((c) => c.id === id);
}

export function getChapterByNumber(num: number): StoryChapter | undefined {
  return ALL_CHAPTERS.find((c) => c.number === num);
}

export function getTotalChapters(): number {
  return ALL_CHAPTERS.length;
}

export function getMissionById(id: string): import('./types').StoryMission | undefined {
  for (const ch of ALL_CHAPTERS) {
    const m = ch.missions.find((mi) => mi.id === id);
    if (m) return m;
  }
  return undefined;
}
